-- Restaurant & Table Management / Subscription & Billing
CREATE TABLE restaurants (
    id          UUID PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    address     VARCHAR(255),
    plan_code   VARCHAR(30)  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- IAM
CREATE TABLE users (
    id             UUID PRIMARY KEY,
    restaurant_id  UUID         NOT NULL REFERENCES restaurants (id),
    name           VARCHAR(120) NOT NULL,
    email          VARCHAR(180) NOT NULL UNIQUE,
    password_hash  VARCHAR(100) NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE dining_tables (
    id             UUID PRIMARY KEY,
    restaurant_id  UUID        NOT NULL REFERENCES restaurants (id),
    label          VARCHAR(60) NOT NULL,
    token          VARCHAR(64) NOT NULL UNIQUE,
    active         BOOLEAN     NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_table_label UNIQUE (restaurant_id, label)
);

-- Dish & Menu Catalog
CREATE TABLE photos (
    id             UUID PRIMARY KEY,
    restaurant_id  UUID        NOT NULL REFERENCES restaurants (id),
    storage_key    VARCHAR(255) NOT NULL,
    content_type   VARCHAR(40) NOT NULL,
    size_bytes     BIGINT      NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE dishes (
    id             UUID PRIMARY KEY,
    restaurant_id  UUID          NOT NULL REFERENCES restaurants (id),
    name           VARCHAR(120)  NOT NULL,
    description    VARCHAR(1000),
    category       VARCHAR(60)   NOT NULL,
    price          NUMERIC(10, 2),
    allergen_free  BOOLEAN       NOT NULL,
    kitchen_notes  VARCHAR(500),
    calories_min   INTEGER,
    calories_max   INTEGER,
    vegetarian     BOOLEAN       NOT NULL,
    vegan          BOOLEAN       NOT NULL,
    photo_id       UUID REFERENCES photos (id),
    model_id       VARCHAR(60),
    status         VARCHAR(20)   NOT NULL,
    available      BOOLEAN       NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_dishes_restaurant ON dishes (restaurant_id);

CREATE TABLE dish_ingredients (
    dish_id     UUID         NOT NULL REFERENCES dishes (id) ON DELETE CASCADE,
    position    INTEGER      NOT NULL,
    ingredient  VARCHAR(80)  NOT NULL,
    PRIMARY KEY (dish_id, position)
);

CREATE TABLE dish_allergens (
    dish_id   UUID        NOT NULL REFERENCES dishes (id) ON DELETE CASCADE,
    allergen  VARCHAR(30) NOT NULL,
    PRIMARY KEY (dish_id, allergen)
);

-- AR Dining Experience (métricas anónimas)
CREATE TABLE interaction_events (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id     UUID        NOT NULL REFERENCES restaurants (id),
    table_id          UUID,
    dish_id           UUID,
    type              VARCHAR(30) NOT NULL,
    duration_seconds  INTEGER,
    occurred_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_events_restaurant_time ON interaction_events (restaurant_id, occurred_at);

-- Landing: solicitudes de piloto
CREATE TABLE leads (
    id               UUID PRIMARY KEY,
    restaurant_name  VARCHAR(120) NOT NULL,
    contact_name     VARCHAR(120) NOT NULL,
    email            VARCHAR(180) NOT NULL,
    phone            VARCHAR(30)  NOT NULL,
    tables           INTEGER      NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
